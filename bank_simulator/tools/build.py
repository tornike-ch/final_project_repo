#!/usr/bin/env python3
"""
Build script.

  python3 tools/build.py

1. Regenerates player/imsmanifest.xml (so player/ is itself an unzipped SCORM package).
2. Writes dist/<packageId>_scorm12.zip with the sample/current content.
3. Writes builder/player_bundle.js, which embeds the player files and the
   default content so the builder can export packages with no server.
"""
import json
import pathlib
import re
import zipfile
from xml.sax.saxutils import escape

ROOT = pathlib.Path(__file__).resolve().parent.parent
PLAYER = ROOT / "player"
DIST = ROOT / "dist"
BUILDER = ROOT / "builder"

# Order matters for nothing but readability; content.js and the manifest are generated.
PLAYER_FILES = [
    "index.html",
    "css/style.css",
    "js/scorm.js",
    "js/engine.js",
    "js/micah.js",
    "js/avatar.js",
    "js/app.js",
]
CONTENT_FILE = "data/content.js"


def load_content():
    text = (PLAYER / CONTENT_FILE).read_text(encoding="utf-8")
    body = re.sub(r"^\s*window\.SIM_CONTENT\s*=\s*", "", text)
    body = re.sub(r";\s*$", "", body.strip())
    return json.loads(body)


def manifest(content, files):
    meta = content.get("meta", {})
    ident = re.sub(r"[^A-Za-z0-9_.-]", "_", meta.get("packageId", "bank-service-simulator"))
    if not re.match(r"^[A-Za-z_]", ident):
        ident = "PKG_" + ident
    title = escape(meta.get("title", "Simulator"))
    file_tags = "\n".join(f'      <file href="{escape(f)}"/>' for f in files)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<manifest identifier="{ident}" version="{escape(str(meta.get('version', '1.0')))}"
  xmlns="http://www.imsproject.org/xsd/imscp_rootv1p1p2"
  xmlns:adlcp="http://www.adlnet.org/xsd/adlcp_rootv1p2"
  xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
  xsi:schemaLocation="http://www.imsproject.org/xsd/imscp_rootv1p1p2 imscp_rootv1p1p2.xsd http://www.imsglobal.org/xsd/imsmd_rootv1p2p1 imsmd_rootv1p2p1.xsd http://www.adlnet.org/xsd/adlcp_rootv1p2 adlcp_rootv1p2.xsd">
  <metadata>
    <schema>ADL SCORM</schema>
    <schemaversion>1.2</schemaversion>
  </metadata>
  <organizations default="ORG-1">
    <organization identifier="ORG-1">
      <title>{title}</title>
      <item identifier="ITEM-1" identifierref="RES-1" isvisible="true">
        <title>{title}</title>
      </item>
    </organization>
  </organizations>
  <resources>
    <resource identifier="RES-1" type="webcontent" adlcp:scormtype="sco" href="index.html">
{file_tags}
    </resource>
  </resources>
</manifest>
"""


def main():
    content = load_content()
    all_files = PLAYER_FILES + [CONTENT_FILE]
    man = manifest(content, all_files)
    (PLAYER / "imsmanifest.xml").write_text(man, encoding="utf-8")

    DIST.mkdir(exist_ok=True)
    pkg = re.sub(r"[^A-Za-z0-9_.-]", "_", content["meta"].get("packageId", "simulator"))
    zip_path = DIST / f"{pkg}_scorm12.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("imsmanifest.xml", man)
        for f in all_files:
            z.write(PLAYER / f, f)

    bundle = {f: (PLAYER / f).read_text(encoding="utf-8") for f in PLAYER_FILES}
    js = (
        "/* GENERATED by tools/build.py - do not edit. Player files + default content for the builder. */\n"
        "window.PLAYER_FILES = " + json.dumps(bundle, ensure_ascii=False).replace("</", "<\\/") + ";\n"
        "window.DEFAULT_CONTENT = " + json.dumps(content, ensure_ascii=False).replace("</", "<\\/") + ";\n"
    )
    (BUILDER / "player_bundle.js").write_text(js, encoding="utf-8")

    print(f"manifest : {PLAYER / 'imsmanifest.xml'}")
    print(f"package  : {zip_path} ({zip_path.stat().st_size // 1024} KB)")
    print(f"bundle   : {BUILDER / 'player_bundle.js'}")


if __name__ == "__main__":
    main()
